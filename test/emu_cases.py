"""Hand-computed p-code test sequences for the Rockwell L39 / R65C19 module.

Expected values come from the documented 6502 / 65C02 behaviour (ADC, SBC, CMP, shifts, flags, stack) and, for the R65C19
additions, from the instruction descriptions in the R65C19 data sheet as summarised in docs/ of the upstream repository.
Registers: A X Y S SP (16 bit, the stack lives in RAM) W I (16 bit); flags are one-byte registers N V B D Iflag Z C.
Memory items: n<size>:<addr>=hex (little-endian value).  `@N` in code = 16-bit LE address (case base + N); `$N` in an
expectation = that address in hex (4 digits).
"""
CASES = []


def case(name, code, init, expect, stop=None):
    n = len(bytes.fromhex(code.replace('@', '00').replace(' ', '')))
    CASES.append((name, code, init, expect, n if stop is None else stop))


